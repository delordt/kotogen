"""Reusing a subtitle instead of transcribing, without getting the language wrong.

A subtitle beside the file is more faithful than a model's transcription and
costs nothing, so the reader must cope with SRT, WebVTT, CRLF, inline tags and
cues on two lines. A video usually comes with its translation instead, which
would fill the transcription with English: hence the language threshold.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from kotogen import i18n
from kotogen.generators import subtitles

SRT = """1
00:00:12,340 --> 00:00:15,900
すみません、駅[えき]はどこですか。

2
00:00:16,000 --> 00:00:19,500
まっすぐ 行[い]って、
右[みぎ]に 曲[ま]がってください。
"""

VTT = """WEBVTT

NOTE This comment must not become a cue.

00:12.340 --> 00:15.900 align:start position:0%
<v Takeshi>おはようございます。

cue-2
00:16.000 --> 00:19.500
<i>今日[きょう]はいい 天気[てんき]ですね。</i>
"""


def write(folder: Path, name: str, content: str, encoding: str = "utf-8") -> Path:
    path = folder / name
    path.write_bytes(content.encode(encoding))
    return path


# ── Reading the two dialects ──────────────────────────────────────────────────

def test_srt_read_with_its_bounds(tmp_path):
    segments = subtitles.read(write(tmp_path, "a.srt", SRT))

    assert len(segments) == 2
    assert segments[0].text == "すみません、駅[えき]はどこですか。"
    assert segments[0].start == pytest.approx(12.34)
    assert segments[0].end == pytest.approx(15.9)


def test_cue_over_two_lines_is_glued_back(tmp_path):
    """A cue cut in two on screen stays ONE cue.

    Lines break on the width of the screen, not on the sentence: split, the card
    would pair a translation with half a sentence.
    """
    segments = subtitles.read(write(tmp_path, "a.srt", SRT))

    assert segments[1].text == "まっすぐ 行[い]って、 右[みぎ]に 曲[ま]がってください。"


def test_vtt_header_comment_and_tags(tmp_path):
    """A WebVTT: optional hour, placement settings, tags, NOTE blocks."""
    segments = subtitles.read(write(tmp_path, "a.vtt", VTT))

    assert len(segments) == 2, "the header and the NOTE are not cues"
    # `<v Takeshi>` falls with the other tags: a speaker's name is not spoken.
    assert segments[0].text == "おはようございます。"
    assert segments[0].start == pytest.approx(12.34)
    assert segments[1].text == "今日[きょう]はいい 天気[てんき]ですね。"


def test_crlf_and_utf8_bom(tmp_path):
    """The ordinary Windows case: CRLF, and a BOM up front."""
    segments = subtitles.read(
        write(tmp_path, "a.srt", SRT.replace("\n", "\r\n"), "utf-8-sig"))

    assert len(segments) == 2
    assert segments[0].text == "すみません、駅[えき]はどこですか。"


def test_shift_jis(tmp_path):
    """A file from a Japanese editor is not in UTF-8, and is read all the same."""
    segments = subtitles.read(write(tmp_path, "a.srt", SRT, "cp932"))

    assert segments[0].text == "すみません、駅[えき]はどこですか。"


def test_one_digit_fraction(tmp_path):
    """`,3` is three TENTHS: read as thousandths, everything would shift."""
    raw = "1\n00:00:01,3 --> 00:00:02,5\nはい。\n"
    segments = subtitles.read(write(tmp_path, "a.srt", raw))

    assert segments[0].start == pytest.approx(1.3)
    assert segments[0].end == pytest.approx(2.5)


def test_hours_are_counted(tmp_path):
    raw = "1\n01:02:03,000 --> 01:02:04,000\nはい。\n"
    segments = subtitles.read(write(tmp_path, "a.srt", raw))

    assert segments[0].start == pytest.approx(3723.0)


def test_end_before_start_gives_no_negative_duration(tmp_path):
    """A hand-retimed file: the text is good, the bounds are not."""
    raw = "1\n00:00:10,000 --> 00:00:08,000\nはい。\n"
    segments = subtitles.read(write(tmp_path, "a.srt", raw))

    assert segments[0].end >= segments[0].start


def test_rolling_cues_are_deduplicated(tmp_path):
    """Automatic subtitles carry the same line over from one cue to the next."""
    raw = ("1\n00:00:01,000 --> 00:00:02,000\nはい。\n\n"
           "2\n00:00:02,000 --> 00:00:03,000\nはい。\n\n"
           "3\n00:00:03,000 --> 00:00:04,000\nいいえ。\n")
    segments = subtitles.read(write(tmp_path, "a.srt", raw))

    assert [s.text for s in segments] == ["はい。", "いいえ。"]


def test_unreadable_file_does_not_raise(tmp_path):
    """A subtitle is a bonus: a failure falls back on Whisper and raises nothing."""
    assert subtitles.read(tmp_path / "missing.srt") == []
    assert subtitles.read(write(tmp_path, "empty.srt", "")) == []
    assert subtitles.read(write(tmp_path, "raw.srt", "some text without bounds")) == []


# ── ASS, the dialect of the fansubs ───────────────────────────────────────────

ASS = r"""[Script Info]
; Script generated by Aegisub
Title: 第1話
ScriptType: v4.00+

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, Bold
Style: Default,ヒラギノ角ゴ,72,&H00FFFFFF,0
Style: Top,ヒラギノ角ゴ,72,&H00FFFFFF,0
Style: Sign,ＭＳ ゴシック,48,&H00FFFFFF,0

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Comment: 0,0:00:00.00,0:00:05.00,Default,,0,0,0,,この行は表示されない
Dialogue: 0,0:00:01.23,0:00:03.45,Default,太郎,0,0,0,,{\an8}おはようございます
Dialogue: 0,0:00:04.00,0:00:06.10,Default,,0,0,0,,今日は町へ\N野菜を買いに行くんだ
Dialogue: 0,0:00:07.00,0:00:08.50,Default,,0,0,0,,{\i1}それは{\i0}1,000円です{TL note}
Dialogue: 0,0:00:02.00,0:00:04.00,Sign,,0,0,0,,{\pos(960,80)}山田商店
Dialogue: 0,0:00:02.10,0:00:03.90,Top,,0,0,0,,{\an8}花子、行ってくるね

[Aegisub Project Garbage]
Active Line: 3
"""

# The head of the events section, as Aegisub writes it.
EVENTS = ("[Events]\n"
          "Format: Layer, Start, End, Style, Name, "
          "MarginL, MarginR, MarginV, Effect, Text\n")


def test_ass_gives_its_dialogue_and_nothing_else(tmp_path):
    """Only the `Dialogue:` lines of `[Events]` are shown; the rest is presentation."""
    segments = subtitles.read(write(tmp_path, "ep01.ass", ASS))

    texts = [s.text for s in segments]
    assert "この行は表示されない" not in texts, "a Comment: line is never shown"
    assert not any("ヒラギノ" in t or "Active" in t for t in texts)
    # `太郎` in the Name field falls like the `<v Name>` of WebVTT.
    assert texts[0] == "おはようございます"
    assert segments[0].start == pytest.approx(1.23)
    assert segments[0].end == pytest.approx(3.45)


def test_ass_overrides_escapes_and_commas(tmp_path):
    """Braces are for the renderer, `\\N` breaks a cue that stays one, and a
    comma in the text does not cut it: the text is the last field, whole."""
    texts = [s.text for s in subtitles.read(write(tmp_path, "ep01.ass", ASS))]

    assert "今日は町へ 野菜を買いに行くんだ" in texts
    assert "それは1,000円です" in texts


def test_ass_events_in_the_order_of_the_screen(tmp_path):
    """A file sorted by style is read back in the order its lines are shown."""
    texts = [s.text for s in subtitles.read(write(tmp_path, "ep01.ass", ASS))]

    assert texts == ["おはようございます", "花子、行ってくるね",
                     "今日は町へ 野菜を買いに行くんだ", "それは1,000円です"]


def test_ass_leaves_out_what_is_written_not_said(tmp_path):
    """A fansub draws its signs, its title card and the karaoke of its credits
    as lines of their own. The transcription holds only what is heard."""
    raw = (EVENTS
           + r"Dialogue: 0,0:00:01.00,0:00:02.00,Sign,,0,0,0,,山田商店" "\n"
           r"Dialogue: 0,0:00:01.00,0:00:02.00,SignTop,,0,0,0,,第一話" "\n"
           r"Dialogue: 0,0:00:01.00,0:00:02.00,OP Romaji,,0,0,0,,aoi sora no shita" "\n"
           r"Dialogue: 0,0:00:01.00,0:00:02.00,TLNote,,0,0,0,,八百屋：野菜を売る店" "\n"
           r"Dialogue: 0,0:00:01.00,0:00:02.00,Rubi,,0,0,0,,かまど" "\n"
           r"Dialogue: 0,0:00:01.00,0:00:02.00,看板,,0,0,0,,営業中" "\n"
           r"Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,{\k20}青{\k30}空" "\n"
           r"Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,fx,{\t(\1c&HFF&)}青空" "\n"
           r"Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,{\p1}m 0 0 l 9 0" "\n"
           r"Dialogue: 0,0:00:03.00,0:00:04.00,Default,,0,0,0,,{\pos(9,99)}行ってきます" "\n")
    segments = subtitles.read(write(tmp_path, "a.ass", raw))

    # A line placed with `\pos` is not a sign on that ground alone: a TV caption
    # converted to ASS places every one of its lines.
    assert [s.text for s in segments] == ["行ってきます"]


def test_a_bilingual_ass_gives_its_japanese(tmp_path):
    """A bilingual release gives each language its own style, at the same instants."""
    raw = (EVENTS
           + "Dialogue: 0,0:00:01.00,0:00:02.00,CN,,0,0,0,,我去镇上买菜\n"
           "Dialogue: 0,0:00:01.00,0:00:02.00,JP,,0,0,0,,町へ野菜を買いに行くよ\n"
           "Dialogue: 0,0:00:03.00,0:00:04.00,CN,,0,0,0,,路上小心\n"
           "Dialogue: 0,0:00:03.00,0:00:04.00,JP,,0,0,0,,気をつけてね\n")
    segments = subtitles.read(write(tmp_path, "a.ass", raw))

    assert [s.text for s in segments] == ["町へ野菜を買いに行くよ", "気をつけてね"]


def test_ass_line_drawn_on_two_layers_is_one_cue(tmp_path):
    """A line styled by stacking its outline and its fill is written twice, on
    two layers, at the same instant."""
    raw = (EVENTS
           + r"Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,{\bord6}はい。" "\n"
           r"Dialogue: 1,0:00:01.00,0:00:02.00,Default,,0,0,0,,{\bord0}はい。" "\n"
           "Dialogue: 0,0:00:02.00,0:00:03.00,Default,,0,0,0,,いいえ。\n")
    segments = subtitles.read(write(tmp_path, "a.ass", raw))

    assert [s.text for s in segments] == ["はい。", "いいえ。"]


def test_ass_fields_in_the_order_the_file_names_them(tmp_path):
    """The `Format:` line of the events is authoritative, and `.ssa` is read by
    the same reader."""
    raw = ("[Events]\n"
           "Format: Marked, Style, Start, End, Name, "
           "MarginL, MarginR, MarginV, Effect, Text\n"
           "Dialogue: Marked=0,Default,0:00:05.00,0:00:06.50,,0000,0000,0000,,こんにちは\n")
    segments = subtitles.read(write(tmp_path, "a.ssa", raw))

    assert segments[0].text == "こんにちは"
    assert segments[0].start == pytest.approx(5.0)
    assert segments[0].end == pytest.approx(6.5)


def test_ass_without_its_format_line(tmp_path):
    """The standard order stands in for a file that forgets to say its own."""
    raw = "[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,はい。\n"

    segments = subtitles.read(write(tmp_path, "a.ass", raw))

    assert [s.text for s in segments] == ["はい。"]


