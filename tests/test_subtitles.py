# ── The language safeguard ────────────────────────────────────────────────────

def test_english_track_turned_down(tmp_path):
    """The common case: the attached track is the translation."""
    write(tmp_path, "ep.mkv", "")
    write(tmp_path, "ep.srt",
          "1\n00:00:01,000 --> 00:00:02,000\nExcuse me, where is the station?\n\n"
          "2\n00:00:03,000 --> 00:00:04,000\nGo straight and turn right.\n")

    track = subtitles.load(tmp_path / "ep.mkv")

    assert not track.segments, "a translation is not a transcription"
    assert [reason for _, reason in track.rejected] == [subtitles.NOT_JAPANESE]


def test_chinese_track_turned_down(tmp_path):
    """Chinese shares the ideographs of Japanese but writes no kana: counted on
    characters alone, an anime's Chinese track would pass for Japanese."""
    write(tmp_path, "ep.mkv", "")
    write(tmp_path, "ep.zh.srt",
          "1\n00:00:01,000 --> 00:00:02,000\n我去镇上买菜。\n\n"
          "2\n00:00:03,000 --> 00:00:04,000\n路上小心。\n")

    track = subtitles.load(tmp_path / "ep.mkv")

    assert not track.segments
    assert [reason for _, reason in track.rejected] == [subtitles.NOT_JAPANESE]


def test_an_ass_in_another_language_is_turned_down_as_such(tmp_path):
    """No Japanese style at all: refused as not Japanese, not as unreadable,
    which would send one looking in the file."""
    write(tmp_path, "ep.mkv", "")
    write(tmp_path, "ep.en.ass",
          EVENTS + "Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,Good morning.\n")

    track = subtitles.load(tmp_path / "ep.mkv")

    assert [reason for _, reason in track.rejected] == [subtitles.NOT_JAPANESE]


def test_a_few_japanese_lines_are_not_enough(tmp_path):
    """An English track almost always carries a little Japanese (a sign, the
    credits): hence a threshold rather than mere presence."""
    lines = [f"{i}\n00:00:0{i},000 --> 00:00:0{i},900\nEnglish line number {i}.\n"
             for i in range(1, 8)]
    lines.append("8\n00:00:08,000 --> 00:00:08,900\n東京[とうきょう]\n")
    write(tmp_path, "ep.mkv", "")
    write(tmp_path, "ep.srt", "\n".join(lines))

    assert not subtitles.load(tmp_path / "ep.mkv").segments


def test_japanese_track_taken_up(tmp_path):
    write(tmp_path, "ep.mkv", "")
    write(tmp_path, "ep.srt", SRT)

    track = subtitles.load(tmp_path / "ep.mkv")

    assert len(track.segments) == 2
    assert track.path.name == "ep.srt"
    assert not track.rejected


def test_the_text_decides_not_the_language_mark(tmp_path):
    """`.ja` orders the attempts, it authorises nothing: the text is what decides.

    Mislabelled files are common: a `.ja.srt` holding English, a bare `.srt`
    holding Japanese.
    """
    write(tmp_path, "ep.mkv", "")
    write(tmp_path, "ep.ja.srt",
          "1\n00:00:01,000 --> 00:00:02,000\nThis one lies about its language.\n")
    write(tmp_path, "ep.srt", SRT)

    track = subtitles.load(tmp_path / "ep.mkv")

    assert track.path.name == "ep.srt"
    assert [p.name for p, _ in track.rejected] == ["ep.ja.srt"]


# ── The file laid beside ──────────────────────────────────────────────────────

def test_order_of_companions(tmp_path):
    """The Japanese mark first, then the bare name, then the rest."""
    write(tmp_path, "ep.mkv", "")
    for name in ("ep.en.srt", "ep.srt", "ep.jpn.srt"):
        write(tmp_path, name, "")

    found = [p.name for p in subtitles.companions(tmp_path / "ep.mkv")]

    assert found == ["ep.jpn.srt", "ep.srt", "ep.en.srt"]


def test_the_youtube_original_track_is_a_japanese_mark(tmp_path):
    """yt-dlp names `ja-orig` the original track, the one asked for: unrecognised,
    it would be tried after the English translation."""
    write(tmp_path, "video.mp4", "")
    for name in ("video.en.vtt", "video.ja-orig.vtt"):
        write(tmp_path, name, "")

    found = [p.name for p in subtitles.companions(tmp_path / "video.mp4")]

    assert found == ["video.ja-orig.vtt", "video.en.vtt"]


def test_a_prefix_does_not_make_a_companion(tmp_path):
    """`ep1.srt` is not the subtitle of `ep10.mkv`, and nothing would say so."""
    write(tmp_path, "ep10.mkv", "")
    write(tmp_path, "ep1.srt", SRT)

    assert subtitles.companions(tmp_path / "ep10.mkv") == []


def test_an_ass_beside_an_episode_replaces_whisper(tmp_path):
    """The format anime subtitles come in, taken for what is said in it."""
    write(tmp_path, "ep.mkv", "")
    write(tmp_path, "ep.ja.ass", ASS)

    track = subtitles.load(tmp_path / "ep.mkv")

    assert track.path.name == "ep.ja.ass"
    assert "山田商店" not in [s.text for s in track.segments], "a sign is not said"


def test_the_srt_is_tried_before_the_ass(tmp_path):
    """Under the same mark, the `.srt` holds only what is said; an `.ass` does not."""
    write(tmp_path, "ep.mkv", "")
    for name in ("ep.ja.ass", "ep.ja.srt"):
        write(tmp_path, name, "")

    found = [p.name for p in subtitles.companions(tmp_path / "ep.mkv")]

    assert found == ["ep.ja.srt", "ep.ja.ass"]


def test_no_companion_at_all(tmp_path):
    """The ordinary case: no subtitle, no refusal to report."""
    write(tmp_path, "ep.mp3", "")

    track = subtitles.load(tmp_path / "ep.mp3")

    assert not track.segments and not track.rejected and track.path is None


@pytest.mark.parametrize("lang", [name for name in i18n.available()
                                  if name != i18n.SOURCE])
@pytest.mark.parametrize("reason", [subtitles.UNREADABLE, subtitles.NOT_JAPANESE])
def test_every_table_says_why_a_subtitle_is_ignored(lang, reason):
    """Held in English and translated where `audio` shows it, out of the scan's sight."""
    assert reason in i18n._load(lang)
